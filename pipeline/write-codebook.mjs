// Writes docs/codebook.md from lib/codebook.mjs, the same source the v2 prompt is built from.
//   npm run codebook

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { DIMENSIONS, MIN_MOMENTS, PATHS } from './lib/common.mjs';
import { MOMENT_CODES, REACTION_CODES, REQUEST_CODES, TURN_DIMENSIONS, WEIGHTS } from './lib/codebook.mjs';

const question = Object.fromEntries(DIMENSIONS.map((dimension) => [dimension.key, dimension]));
const sideLabel = (side) => (side === 'user' ? 'your side' : side === 'ai' ? 'AI side' : 'not counted');

const lines = [
  '# Codebook',
  '',
  '<!-- Generated by `npm run codebook` from pipeline/lib/codebook.mjs. Edit that file, not this one. -->',
  '',
  'What each dashboard dimension measures and how one conversation is coded. The model (prompt v2) records observable evidence; the positions are computed from it with a fixed formula. Approach after Yeomans, Boland, Collins, Abi-Esber & Brooks (2023), *A Practical Guide to Conversation Research*.',
  '',
  '## How a position is computed',
  '',
  '- **Moments** (six dimensions): each one is an event at one message, credited to you or to AI, and weighted major (' + WEIGHTS.major + ') or minor (' + WEIGHTS.minor + ').',
  '- **Turn codes** (checking, understanding): every one of your messages gets a `reaction` to the AI message before it and a `request` code.',
  '- **Position** = 100 × your weight / (your weight + AI weight). 0 = AI side, 100 = your side. When nothing was counted, the dimension did not happen in that chat and is left out of the averages.',
  '- **Band** in a chat: the split in the first half versus the second half of the conversation.',
  `- **Dashboard**: a dimension counts in a chat only when it came up at least ${MIN_MOMENTS} times there (moments, or counted turns); a single borderline moment flips too easily between runs. The dot is the mean over those chats, and the band is the middle half (25th–75th percentile). Each slider and trend line has a footnote with how many chats it rests on and how repeatable the coding was in the eval.`,
  ''
];

for (const code of MOMENT_CODES) {
  const meta = question[code.key];
  lines.push(`## ${meta.label} (\`${code.key}\`)`, '', `**${meta.question}**`, '', code.definition, '', `**Credit:** ${code.credit}`, '');
  lines.push('**Counts:**', ...code.counts.map((item) => `- ${item}`), '');
  lines.push('**Does not count:**', ...code.not.map((item) => `- ${item}`), '');
  lines.push('**Examples:**', ...code.examples.map((item) => `- ${item}`), '');
}

for (const dimension of TURN_DIMENSIONS) {
  const meta = question[dimension.key];
  lines.push(`## ${meta.label} (\`${dimension.key}\`)`, '', `**${meta.question}**`, '', dimension.definition, '');
  lines.push(`| \`${dimension.field}\` code | Meaning | Counts for |`, '|---|---|---|');
  for (const code of dimension.codes) lines.push(`| \`${code.key}\` | ${code.definition} | ${sideLabel(code.side)} |`);
  lines.push('');
}

lines.push('## All turn codes', '', 'Every user message is coded once with both fields.', '');
lines.push('`reaction`: ' + REACTION_CODES.map((code) => `\`${code.key}\``).join(', ') + '.', '');
lines.push('`request`: ' + REQUEST_CODES.map((code) => `\`${code.key}\``).join(', ') + '.', '');

const out = path.join(PATHS.root, 'docs', 'codebook.md');
await mkdir(path.dirname(out), { recursive: true });
await writeFile(out, lines.join('\n'));
console.log(`Wrote ${path.relative(PATHS.root, out)}`);
